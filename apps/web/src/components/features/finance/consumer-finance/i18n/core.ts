const copy: Record<FinanceLocale, FinanceCoreCopy> = { en, uk, ru };

export function normalizeFinanceLocale(value?: string | null): FinanceLocale {
  const normalized = value?.toLowerCase().split("-")[0];
  return supportedFinanceLocales.includes(normalized as FinanceLocale)
    ? (normalized as FinanceLocale)
    : "en";
}

export function financeCoreCopy(locale?: string | null): FinanceCoreCopy {
  return copy[normalizeFinanceLocale(locale)];
}

export function financeIntlLocale(locale: FinanceLocale) {
  return locale === "uk" ? "uk-UA" : locale === "ru" ? "ru-RU" : "en-US";
}
