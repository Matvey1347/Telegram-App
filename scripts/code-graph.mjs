#!/usr/bin/env node

import { createServer } from 'node:http';
import { existsSync, readFileSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const output = join(root, 'graphify-out');
const html = join(output, 'graph.html');
const command = process.argv[2] ?? 'help';
const args = process.argv.slice(3);

function printHelp() {
  console.log(`Graphify helper for ${root}

Usage: pnpm graph <command>

Commands:
  build       Build/update the local Graphify graph and standard HTML visualization
  update      Incrementally refresh the graph from code (no LLM/API key required)
  watch       Watch source files and refresh graph.json + graph.html on changes
  serve       Serve Graphify's graph.html at http://localhost:8000/
  query ...   Pass a query to Graphify, e.g. pnpm graph query "how does auth reach the DB?"
  path ...    Pass a path request, e.g. pnpm graph path "A" "B"
  explain ... Explain a node, e.g. pnpm graph explain "TelegramChannelService"

The graph and HTML are generated by Graphify in graphify-out/.`);
}

function runGraphify(graphifyArgs) {
  const result = spawnSync('graphify', graphifyArgs, {
    cwd: root,
    stdio: 'inherit',
  });
  if (result.error) {
    console.error(`Could not start Graphify: ${result.error.message}`);
    process.exitCode = 1;
  } else if (result.status !== 0) {
    process.exitCode = result.status ?? 1;
  }
}

if (command === 'help' || command === '--help') {
  printHelp();
} else if (command === 'build') {
  runGraphify(['update', root, ...args]);
} else if (command === 'update') {
  runGraphify(['update', root, ...args]);
} else if (command === 'watch') {
  runGraphify(['watch', root, ...args]);
} else if (['query', 'path', 'explain', 'affected', 'god-nodes'].includes(command)) {
  runGraphify([command, ...args]);
} else if (command === 'serve') {
  if (!existsSync(html)) {
    console.error('Graphify HTML is missing. Run `pnpm graph build` first.');
    process.exitCode = 1;
  } else {
    const port = Number(process.env.GRAPH_PORT ?? 8000);
    const server = createServer((request, response) => {
      if (request.url !== '/' && request.url !== '/graph.html') {
        response.writeHead(404).end('Not found');
        return;
      }
      try {
        response.writeHead(200, { 'content-type': 'text/html; charset=utf-8' });
        response.end(readFileSync(html));
      } catch (error) {
        response.writeHead(500).end(`Could not read Graphify HTML: ${error.message}`);
      }
    });
    server.listen(port, '127.0.0.1', () => {
      console.log(`Serving Graphify's standard visualization at http://localhost:${port}/`);
      console.log('Press Ctrl+C to stop.');
    });
  }
} else {
  console.error(`Unknown graph command: ${command}`);
  printHelp();
  process.exitCode = 2;
}
